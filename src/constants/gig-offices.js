const slug = (text) =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

export const GIG_STATES = Object.keys(GIG_OFFICES);

// Flat list of offices for a state: { id, name, address, town, state }
export const getOffices = (state) => {
  const towns = GIG_OFFICES[state];
  if (!towns) return [];
  return Object.entries(towns).flatMap(([town, addresses]) =>
    addresses.map((address, index) => ({
      id: `${slug(state)}-${slug(town)}-${index + 1}`,
      name: addresses.length > 1 ? `${town} ${index + 1}` : town,
      address,
      town,
      state,
    }))
  );
};

export const findOffice = (state, id) =>
  getOffices(state).find((office) => office.id === id) ?? null;
